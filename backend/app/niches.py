def get_niche_overlay_type(niche_id_or_title: str) -> str | None:
    """Return 'numbered', 'stage', or None for a given niche ID or title."""
    if not niche_id_or_title:
        return None
    val = niche_id_or_title.lower().strip()
    for o_type, keywords in FIXED_OVERLAY_MAPPING.items():
        for kw in keywords:
            if kw.lower() in val or val in kw.lower():
                return o_type
    return None


def get_all_niches() -> List[Dict[str, Any]]:
    """Return list of all 7 domain categories and 20 sub-niches."""
    return DOMAINS_DATA


def find_niche_info(niche_id: str) -> Dict[str, Any]:
    """Find specific niche config by ID or return custom placeholder config."""
    niche_data = None
    for domain in DOMAINS_DATA:
        for sub in domain["sub_niches"]:
            if sub["id"] == niche_id or sub["title"] == niche_id:
                niche_data = dict(sub)
                break
        if niche_data:
            break

    if not niche_data:
        niche_data = {
            "id": niche_id,
            "title": niche_id,
            "script_style": "سردي متناسق",
            "sources": "pexels_video, pixabay_video",
            "music_mood": "سينمائي هادئ",
            "clip_duration_limit": 6,
            "desc": "نيتش مخصص",
        }

    # Automatically set section_overlay_type if not explicitly set
    if "section_overlay_type" not in niche_data or not niche_data["section_overlay_type"]:
        found_overlay = get_niche_overlay_type(niche_id) or get_niche_overlay_type(str(niche_data.get("title", "")))
        if found_overlay:
            niche_data["section_overlay_type"] = found_overlay

    return niche_data

